SELECT
  DATE_DIFF(DATE '2025-08-15', DATE '2025-01-01', DAY) AS days,
  DATE_DIFF(DATE '2025-08-15', DATE '2025-01-01', MONTH) AS months,
  DATE_DIFF(DATE '2025-08-15', DATE '2025-01-01', WEEK) AS weeks,
  DATE_DIFF(DATE '2025-08-15', DATE '2025-01-01', YEAR) AS years,
  DATETIME_DIFF(DATETIME '2025-08-15T12:30:00', DATETIME '2025-08-15T10:00:00', MINUTE) AS minutes
